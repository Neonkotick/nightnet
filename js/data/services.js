export function getServiceById(id) {
  return SERVICES.find(s => s.id === id) || null;
}

export function filterServices({ category = 'all', search = '', sort = 'popularity' } = {}) {
  let list = [...SERVICES];

  if (category && category !== 'all') {
    list = list.filter(s => s.category === category);
  }

  if (search && search.trim()) {
    const q = search.toLowerCase().trim();
    list = list.filter(s =>
      s.name.toLowerCase().includes(q) ||
      s.short.toLowerCase().includes(q) ||
      s.description.toLowerCase().includes(q) ||
      s.options.some(o => o.toLowerCase().includes(q))
    );
  }

  switch (sort) {
    case 'price':
      list.sort((a, b) => a.price - b.price);
      break;
    case 'price-desc':
      list.sort((a, b) => b.price - a.price);
      break;
    case 'rating':
      list.sort((a, b) => b.rating - a.rating);
      break;
    case 'response':
      // rough: shorter first
      list.sort((a, b) => a.responseTime.localeCompare(b.responseTime));
      break;
    case 'risk':
      const riskOrder = { LOW: 0, MEDIUM: 1, HIGH: 2, CRITICAL: 3 };
      list.sort((a, b) => (riskOrder[a.risk] || 0) - (riskOrder[b.risk] || 0));
      break;
    case 'popularity':
    default:
      list.sort((a, b) => b.orders - a.orders);
      break;
  }

  return list;
}
